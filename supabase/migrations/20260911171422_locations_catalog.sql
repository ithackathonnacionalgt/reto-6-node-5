create table public.departments (
  code text primary key,
  name text not null unique,
  constraint departments_code_format check (code ~ '^[0-9]{2}$')
);

create table public.municipalities (
  code text primary key,
  department_code text not null references public.departments(code)
    on update cascade
    on delete restrict,
  name text not null,
  constraint municipalities_code_format check (code ~ '^[0-9]{4}$'),
  constraint municipalities_code_department_match check (left(code, 2) = department_code),
  constraint municipalities_department_name_unique unique (department_code, name)
);

